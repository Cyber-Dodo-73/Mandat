/**
 * Generates src/features/profile/cosmetics.generated.ts: one require() per cosmetic image found
 * under assets/images/{avatars,banners,badges}/<id>.png (names from docs/ART_PROMPTS.md). Missing
 * images are simply absent from the maps and the app draws a procedural fallback instead.
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const imagesDir = join(here, '..', 'assets', 'images');
const target = join(here, '..', 'src', 'features', 'profile', 'cosmetics.generated.ts');

const KINDS = ['avatars', 'banners', 'badges'] as const;
type Kind = (typeof KINDS)[number];

function files(kind: Kind): string[] {
  const dir = join(imagesDir, kind);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((file) => file.endsWith('.png'))
    .sort();
}

function entries(kind: Kind): string {
  return files(kind)
    .map((file) => `  '${file.slice(0, -4)}': require('../../../assets/images/${kind}/${file}'),`)
    .join('\n');
}

const output = `// Generated by scripts/sync-cosmetics.ts from assets/images/: do not edit.
// Values are Metro asset ids (what require() returns for an image).

/** Avatar images by id suffix (\`avatar.level_15\` → \`level_15\`). */
export const avatarImages: Record<string, number> = {
${entries('avatars')}
};

/** Banner images by id suffix (\`banner.default\` → \`default\`). */
export const bannerImages: Record<string, number> = {
${entries('banners')}
};

/** Achievement badge images by family (\`packs\`, \`rarity_mythic\`…). */
export const badgeImages: Record<string, number> = {
${entries('badges')}
};
`;

writeFileSync(target, output.replace(/\{\n\n\}/g, '{}'));
console.log(
  `Synced cosmetics (${KINDS.map((kind) => `${kind}: ${files(kind).length}`).join(', ')}) to ${target}`,
);
