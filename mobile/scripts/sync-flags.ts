/**
 * Writes src/data/flags.generated.ts: the real flag (SVG, 3:2) of every country in the card
 * catalog, from country-flag-icons (MIT). Only the countries we need are bundled, offline.
 *   npm run sync:flags
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const catalogPath = join(here, '..', 'src', 'data', 'cards.season1.json');
const output = join(here, '..', 'src', 'data', 'flags.generated.ts');

type CatalogFile = { cards: { country: string }[] } | { country: string }[];
const catalog = JSON.parse(readFileSync(catalogPath, 'utf8')) as CatalogFile;
const cards = Array.isArray(catalog) ? catalog : catalog.cards;
const codes = [...new Set(cards.map((card) => card.country.toUpperCase()))].sort();

const flagsDir = join(dirname(require.resolve('country-flag-icons/package.json')), 'string', '3x2');
const missing: string[] = [];
const entries: string[] = [];
for (const code of codes) {
  try {
    const source = readFileSync(join(flagsDir, `${code}.js`), 'utf8');
    const match = /export default '(.*)'\s*;?\s*$/s.exec(source.trim());
    if (!match?.[1]) throw new Error('unexpected format');
    entries.push(`  ${code}: ${JSON.stringify(match[1].replace(/\\'/g, "'"))},`);
  } catch {
    missing.push(code);
  }
}

writeFileSync(
  output,
  [
    '// Generated by scripts/sync-flags.ts from country-flag-icons (MIT). Do not edit.',
    '/** Flag SVG (3:2) per ISO 3166-1 alpha-2 code, for every country of the catalog. */',
    'export const FLAG_SVGS: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n'),
);
console.log(`Wrote ${entries.length} flags to ${output}${missing.length ? `; missing: ${missing.join(', ')}` : ''}`);
