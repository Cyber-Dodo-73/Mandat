/**
 * Generates src/data/portraits.ts from data/portraits.manifest.json: one bundled image per
 * card (mobile/assets/portraits/<cardId>.webp, produced by `npm run build -- portraits-web`
 * in scripts/build-cards) and the attribution required by each Commons license.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type ManifestEntry = {
  cardId: string;
  name: string;
  file: string | null;
  sourcePage: string | null;
  license: string | null;
  licenseUrl: string | null;
  artist: string | null;
  credit: string | null;
  attributionRequired: boolean | null;
  category: string;
};

const here = dirname(fileURLToPath(import.meta.url));
const manifestPath = join(here, '..', '..', 'data', 'portraits.manifest.json');
const assetsDir = join(here, '..', 'assets', 'portraits');
const target = join(here, '..', 'src', 'data', 'portraits.ts');

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as { portraits: ManifestEntry[] };
const entries = manifest.portraits
  .filter((entry) => existsSync(join(assetsDir, `${entry.cardId}.webp`)))
  .sort((a, b) => a.cardId.localeCompare(b.cardId));

const clean = (value: string | null) => (value ? value.replace(/\s+/g, ' ').trim() : null);

const images = entries
  .map((entry) => `  '${entry.cardId}': require('../../assets/portraits/${entry.cardId}.webp'),`)
  .join('\n');

const credits = entries.map((entry) => ({
  cardId: entry.cardId,
  name: entry.name,
  artist: clean(entry.artist) ?? clean(entry.credit),
  license: clean(entry.license),
  licenseUrl: entry.licenseUrl,
  sourcePage: entry.sourcePage,
  // Unknown on Commons: credit the author anyway unless the work is in the public domain.
  attributionRequired: entry.attributionRequired ?? entry.category !== 'public_domain',
  publicDomain: entry.category === 'public_domain',
}));

const output = `// Generated by scripts/sync-portraits.ts from data/portraits.manifest.json: do not edit.
import type { ImageSourcePropType } from 'react-native';

export type PortraitCredit = {
  cardId: string;
  /** Person shown, in English (as named on Wikidata). */
  name: string;
  artist: string | null;
  license: string | null;
  licenseUrl: string | null;
  sourcePage: string | null;
  attributionRequired: boolean;
  publicDomain: boolean;
};

/** Bundled portrait of each card that has one (Wikimedia Commons, resized to WebP). */
export const portraits: Readonly<Record<string, ImageSourcePropType>> = {
${images}
};

export const portraitCredits: readonly PortraitCredit[] = ${JSON.stringify(credits, null, 2)};
`;

writeFileSync(target, output);
console.log(`Generated ${target}: ${entries.length} portraits`);
